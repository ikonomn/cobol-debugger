"""Map GnuCOBOL generated C debug locations back to COBOL statements."""
from pathlib import Path
import re

MARKER = re.compile(r'/\*\s*Line:\s*(\d+)\s*:(.*?)\s*:\s*(.*?)\s*\*/')
DIRECTIVE = re.compile(r'^\s*#\s*(?:line\s+)?(\d+)\s+"([^"]+)"')

class SourceMap:
    def __init__(self):
        self.cache = {}
        self.details = {}

    def location(self, filename, line):
        path = Path(filename)
        if path.suffix.lower() != '.c':
            return None
        try:
            stat = path.stat()
            version = (stat.st_mtime_ns, stat.st_size)
            cached = self.cache.get(str(path))
            if cached is None or cached[0] != version:
                text = path.read_text(encoding='utf-8', errors='replace')
                # Never interpret arbitrary C comments as COBOL mapping metadata.
                if not re.search(r'/\* Generated by\s+cobc\b', text):
                    return None
                mapping = {}
                details = {}
                statement_id = None
                current = None
                logical_file, logical_line = path.name, 1
                for physical, content in enumerate(text.splitlines(), 1):
                    marker = MARKER.search(content)
                    if marker:
                        number, statement, source = marker.groups()
                        statement_id = None if ('entry' in statement.lower() or int(number) <= 0 or 'last source line' in statement.lower()) else f'{path.resolve()}:{physical}'
                        source_path = Path(source)
                        if not source_path.is_absolute():
                            source_path = path.parent / source_path
                        current = None if 'last source line' in statement.lower() else {
                            'file': str(source_path.resolve()), 'line': int(number)}
                    directive = DIRECTIVE.match(content)
                    if directive:
                        logical_line = int(directive[1])
                        logical_file = directive[2]
                        continue
                    if current:
                        # GDB reports the logical line established by #line.
                        if Path(logical_file).name == path.name:
                            mapping[logical_line] = current.copy()
                            if statement_id:
                                details[logical_line] = {**current, 'statement_id': statement_id}
                    logical_line += 1
                self.cache[str(path)] = (version, mapping)
                self.details[str(path)] = details
            return self.cache[str(path)][1].get(int(line))
        except (OSError, ValueError):
            return None

    def statement(self, filename, line):
        if self.location(filename, line) is None:
            return None
        return self.details.get(str(Path(filename)), {}).get(int(line))
