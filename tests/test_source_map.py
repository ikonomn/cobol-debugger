from pathlib import Path
import tempfile
import unittest
from cobgdb_python.source_map import SourceMap

class SourceMapTests(unittest.TestCase):
    def test_logical_lines_and_windows_source_colon(self):
        with tempfile.TemporaryDirectory() as folder:
            c = Path(folder) / 'sample.c'
            source = Path(folder) / 'sample.cob'
            c.write_text(f'''/* Generated by           cobc 3.3 */
/* Line: 7 : ADD : {source} */
#line 7 "{source}"
statement;
#line 105 "sample.c"
trace;
add;
/* Line: 8 : DISPLAY : {source} */
#line 8 "{source}"
statement;
#line 200 "sample.c"
display;
''')
            mapper = SourceMap()
            self.assertEqual(mapper.location(c, 105), {'file': str(source), 'line': 7})
            self.assertEqual(mapper.location(c, 106)['line'], 7)
            self.assertEqual(mapper.location(c, 200)['line'], 8)
            self.assertIsNone(mapper.location(c, 500))
            c.write_text('/* ordinary C */')
            self.assertIsNone(mapper.location(c, 105))

    def test_missing_file(self):
        self.assertIsNone(SourceMap().location('/missing/file.c', 10))
