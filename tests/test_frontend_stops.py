import json
from pathlib import Path
from unittest.mock import patch

import pytest

pytest.importorskip('PyQt5')
from cobgdb_python import frontend


_app = None


@pytest.fixture
def window():
    global _app
    _app = frontend.QApplication.instance() or frontend.QApplication([])
    with patch.object(frontend.QProcess, 'start'), patch.object(
        frontend, 'SessionLog', side_effect=OSError('test')
    ):
        viewer = frontend.Window()
    viewer.session_loaded = True
    viewer.workflow_started = True
    yield viewer
    viewer.close()
    _app.processEvents()


def receive(window, **message):
    window.handle_line(json.dumps(message).encode())


def test_stack_button_displays_nested_and_flat_frames(window):
    receive(window, event='stopped', location=None)
    window.buttons['stack'].click()
    receive(window, id=window.counter, ok=True, result={'stack': [
        {'frame': {'level': '0', 'func': 'score_', 'file': 'score.cob',
                   'fullname': '/project/score.cob', 'line': '9'}},
        {'level': '1', 'func': 'main', 'file': 'score.c', 'line': '33'},
    ]})
    assert window.stack_dialog.isVisible()
    assert window.stack_table.rowCount() == 2
    assert [window.stack_table.item(0, col).text() for col in range(4)] == [
        '0', 'score_', '/project/score.cob', '9',
    ]
    assert window.stack_table.item(1, 1).text() == 'main'


def test_finish_clears_variables_and_discards_late_response(window, tmp_path):
    cobol = tmp_path / 'score.cob'
    cobol.write_text('       display 1\n')
    generated = tmp_path / 'score.c'
    generated.write_text('/* Generated by           cobc 3.3 */\n')
    location = {'file': str(cobol), 'line': 1}
    receive(window, event='stopped', location=location)
    assert window.buttons['variables'].isEnabled()
    first_request = window.counter
    available = {'name': 'score', 'value': '4', 'format': 'numeric DISPLAY'}
    unavailable = {'name': 'selection', 'value': '<unavailable>', 'format': ''}
    receive(window, id=first_request, ok=True,
            result={'variables': [available, unavailable]})
    assert window.variables_table.rowCount() == 1
    window.buttons['variables'].click()
    pending_request = window.counter

    receive(window, event='stopped', reason='function-finished', location=None,
            source_mapping='unavailable', frame={'fullname': str(generated), 'line': '52'})
    assert window.counter == pending_request
    assert not window.buttons['variables'].isEnabled()
    assert window.source_path == str(cobol)
    assert not window.source.extraSelections()
    receive(window, id=pending_request, ok=True, result={'variables': [available]})
    assert window.variables_table.rowCount() == 0
    receive(window, event='stopped', location=location)
    assert window.buttons['variables'].isEnabled()
    assert window.counter == pending_request + 1


def test_step_into_opens_original_c_helper_at_line_23(window):
    source = Path(__file__).resolve().parents[1] / 'examples/gui/score_window.c'
    cobol = source.with_name('score.cob')
    window.show_source(str(cobol), 9)
    receive(window, event='stopped', reason='end-stepping-range', location=None,
            source_mapping='unavailable',
            frame={'fullname': str(source), 'file': source.name, 'line': '23',
                   'func': 'choose_score'})
    assert window.source_path == str(cobol)
    assert not window.source.extraSelections()
    assert window.c_source_dialog.isVisible()
    assert window.c_source_dialog.windowTitle() == f'{source} — C line 23'
    assert window.c_source.textCursor().blockNumber() == 22
    assert window.c_source.extraSelections()[0].cursor.blockNumber() == 22
    assert window.counter == 0
