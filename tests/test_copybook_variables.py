from pathlib import Path
import tempfile
import unittest
from cobgdb_python.backend import Debugger

class CopybookVariablesTests(unittest.TestCase):
    def test_first_copybook_stop_and_function_cache(self):
        with tempfile.TemporaryDirectory() as folder:
            member=Path(folder)/'member.cpy'
            generated=Path(folder)/'main.c'
            generated.write_text(f'''/* Generated by cobc 3.3 */
#line 1 "{member}"
static const cob_field_attr a_1 = {{0x10, 4, 0, 0x0000, NULL}};
static cob_field f_1 = {{4, b_1, &a_1}}; /* YEAR */
''')
            debugger=Debugger(lambda _:None)
            debugger.last_frame={'fullname':str(member),'func':'MAIN_'}
            requests=[]
            def command(text):
                requests.append(text)
                if text=='-file-list-exec-source-files':
                    return {'files':[{'fullname':str(generated)}]}
                return {'memory':[{'contents':'32303331'}]}
            debugger.command=command
            self.assertEqual(debugger.cobol_variables()['variables'][0]['value'],'2031')
            debugger.last_frame['fullname']=str(Path(folder)/'other.cpy')
            self.assertEqual(debugger.cobol_variables()['variables'][0]['name'],'YEAR')
            self.assertEqual(requests.count('-file-list-exec-source-files'),1)
